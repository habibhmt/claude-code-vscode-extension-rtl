const MARK = /^[\p{Mn}\p{Me}\p{Cf}\p{Cc}\p{Default_Ignorable_Code_Point}]$/u
const EMOJI_PRESENTATION = /^\p{Emoji_Presentation}$/u
const PICTOGRAPHIC = /\p{Extended_Pictographic}/u
const MODIFIER = /[\u{1F3FB}-\u{1F3FF}]/u
const TAG = /[\u{E0020}-\u{E007F}]/u
const REGIONAL_PAIR = /^[\u{1F1E6}-\u{1F1FF}]{2}$/u

function inRanges(table: number[], cp: number): boolean {
  let lo = 0
  let hi = table.length / 2 - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    if (cp < table[mid * 2]) hi = mid - 1
    else if (cp > table[mid * 2 + 1]) lo = mid + 1
    else return true
  }
  return false
}

export function scalarWidth(cp: number): number {
  if (cp === 0x115f) return 1 // the Hangul choseong filler: measured 1, although default-ignorable
  if (cp === 0x20e3) return 2 // a lone combining keycap: measured 2
  const ch = String.fromCodePoint(cp)
  if (MARK.test(ch) || inRanges(ZERO, cp)) return 0
  if (inRanges(WIDE, cp) || (EMOJI_PRESENTATION.test(ch) && !(cp >= 0x1f1e6 && cp <= 0x1f1ff))) return 2 // a lone regional indicator is 1
  return 1
}

export function clusterWidth(cluster: string): number {
  if (cluster.length === 0) return 0
  const multi = cluster.length > String.fromCodePoint(cluster.codePointAt(0)!).length
  if (multi && (cluster.includes('\uFE0F') || cluster.includes('\u20E3') || REGIONAL_PAIR.test(cluster) || TAG.test(cluster) || (PICTOGRAPHIC.test(cluster) && (cluster.includes('\u200D') || MODIFIER.test(cluster))))) return 2
  let w = 0
  for (const ch of cluster) w += scalarWidth(ch.codePointAt(0)!)
  return w
}

export function textWidth(text: string): number {
  let w = 0
  for (const g of graphemes(text)) w += clusterWidth(g)
  return w
}
