/** عنوان‌های لازمِ قالب؛ اگر جواب هیچ‌کدام را نداشت یعنی مدل از نقش بیرون زد. */
export const REQUIRED_HEADINGS = ['## خرجِ بی‌مصرف', '## تنظیمِ بهتر', '## کمک‌های دیگر']

/** آیا جواب قالب را رعایت کرده؟ دست‌کم دو عنوان از سه. */
export function followsFormat(content) {
  const text = String(content || '')
  return REQUIRED_HEADINGS.filter((heading) => text.includes(heading)).length >= 2
}
