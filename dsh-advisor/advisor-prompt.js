/**
 * پیام‌های OpenRouter — ترتیبِ کش‌دوست.
 * @param input - خروجیِ buildAdvisorInput.
 * @param instruction - دستورِ همین اجرا (آخرین چیز).
 * @returns [{role:'system'},{role:'user', content: prefix + tail + instruction}]
 */
export function buildMessages(input, instruction) {
  const value = input && typeof input === 'object' ? input : {}
  const tail = String(value.tail || '')
  const order = String(instruction || '')
  const data = String(value.prefix || '') + tail
  if (!order) return [{ role: 'system', content: SYSTEM_PROMPT }, { role: 'user', content: data }]
  // دستور در نوبتِ جدا، بعد از یک «رسید»ِ کوتاهِ دستیار: مرزِ نقش روشن می‌شود.
  // بی‌این، روی چتِ ۹۰۰ هزار توکنی مدل دو بار پشتِ سرِ هم خودش چت را ادامه داد (۱۵ نوامبر).
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    { role: 'user', content: data },
    { role: 'assistant', content: DATA_ACK },
    { role: 'user', content: order },
  ]
}

