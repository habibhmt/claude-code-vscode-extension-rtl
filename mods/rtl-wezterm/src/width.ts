// Terminal cell widths per grapheme cluster, matching what Claude Code's renderer measures.
//
// The renderer emits one row per visual line and must never hand Ink a row wider than its box
// (Ink would wrap it a second time). Claude Code 2.1.288 measures text with
// `Bun.stringWidth(text, { ambiguousIsNarrow: true })` of its embedded Bun 1.4.3. That function is
// not reachable from the hooks VM, so this module reproduces it:
// - per scalar: the wide ranges below (East Asian Wide/Fullwidth and emoji presentation, taken from
//   Bun 1.3.14's table, the closest public release, plus the late emoji blocks) are 2 cells;
//   nonspacing and enclosing marks (Mn, Me), format and control characters, default-ignorables,
//   and the zero ranges below (Bun's zero-width spacing marks, Hangul medial/final jamo, some
//   unassigned Indic points) are 0; everything else, ambiguous-width included, is 1;
// - per cluster: an emoji sequence (VS16, keycap, a regional-indicator pair, a skin-tone modifier,
//   a ZWJ sequence, a tag sequence) is 2; any other cluster is the sum of its scalars.
// Checked cell by cell against the live 2.1.288 renderer (tests/fixtures/ink-widths-2.1.288.json); where Bun
// 1.4.3 differs from 1.3.14 the measurement wins (Hebrew and Arabic points are 0, Hangul fillers,
// newer emoji).

const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' })

export function graphemes(text: string): string[] {
  const out: string[] = []
  for (const s of segmenter.segment(text)) out.push(s.segment)
  return out
}

